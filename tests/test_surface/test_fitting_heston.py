def test_the_price_objective_also_fits_the_surface() -> None:
    fitted = HestonCalibrator(objective="price", n_starts=2).fit(_observations())
    predicted = fitted.implied_volatility(_observations().k, _observations().T)
    resolved = np.isfinite(predicted)
    rmse = float(np.sqrt(np.mean((predicted[resolved] - _observations().iv[resolved]) ** 2)))
    # A price residual is dominated by at-the-money vega, so the implied-vol fit
    # it produces is looser than the implied-vol objective's -- which is exactly
    # why the latter is the default.
    assert rmse < 1e-2


