"""The Heston surface: no market needed, wings declined honestly, parameters recovered."""

from __future__ import annotations

import json

import numpy as np
import pytest

from fast_vollib.surface import (
    SurfaceGridSpec,
    SurfaceMarket,
    SurfaceObservations,
    SurfacePoints,
    materialize_surface,
)
from fast_vollib.surface.errors import SurfaceCalibrationError, SurfaceValidationError
from fast_vollib.surface.fitting.heston import (
    DEFAULT_IV_UNCERTAINTY_TOLERANCE,
    PRICE_NOISE_PER_UNIT_FORWARD,
    HestonCalibrator,
    HestonIVSurface,
    HestonParameters,
)
from fast_vollib.surface.protocols import DefiniteIVSurface, SurfaceCalibrator

TRUTH = HestonParameters(v0=0.045, kappa=1.8, theta=0.055, vol_of_vol=0.55, rho=-0.65)
MATURITIES = (0.08, 0.17, 0.25, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0)

#: Parameter recovery from noiseless data generated by the same code path.  The
#: binding constraint is the solver's own convergence criterion together with the
#: finite-difference step; measured worst case over the five parameters is 8e-7.
RECOVERY_TOL = 5e-6

#: How closely the fitted surface must reproduce the implied volatilities it was
#: fitted to.  Measured at 1e-8 -- eight decimal places of a volatility.
FIT_TOL = 1e-6


def _observations(parameters: HestonParameters = TRUTH, n_k: int = 21, span: float = 0.45):
    surface = HestonIVSurface(parameters=parameters)
    k = np.tile(np.linspace(-span, span, n_k), len(MATURITIES))
    T = np.repeat(MATURITIES, n_k)
    iv = surface.implied_volatility(k, T)
    resolved = np.isfinite(iv)
    return SurfaceObservations(k=k[resolved], T=T[resolved], iv=iv[resolved])


