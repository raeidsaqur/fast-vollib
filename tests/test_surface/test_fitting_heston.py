# --- calibration ---------------------------------------------------------------


def test_calibration_recovers_the_parameters_it_was_generated_from() -> None:
    fitted = HestonCalibrator().fit(_observations())
    for name, value in TRUTH.as_mapping().items():
        assert abs(getattr(fitted.parameters, name) - value) < RECOVERY_TOL, name


def test_the_fitted_surface_reproduces_the_quotes_it_was_fitted_to() -> None:
    observations = _observations()
    fitted = HestonCalibrator().fit(observations)
    predicted = fitted.implied_volatility(observations.k, observations.T)
    resolved = np.isfinite(predicted)
    rmse = float(np.sqrt(np.mean((predicted[resolved] - observations.iv[resolved]) ** 2)))
    assert rmse < FIT_TOL, rmse


def test_calibration_is_deterministic() -> None:
    observations = _observations()
    first = HestonCalibrator().fit(observations)
    second = HestonCalibrator().fit(observations)
    assert first.parameters.as_mapping() == second.parameters.as_mapping()


def test_the_calibrator_holds_no_state_between_fits() -> None:
    calibrator = HestonCalibrator(n_starts=1)
    other = HestonParameters(v0=0.02, kappa=3.0, theta=0.03, vol_of_vol=0.4, rho=-0.4)
    first = calibrator.fit(_observations())
    calibrator.fit(_observations(other))
    third = calibrator.fit(_observations())
    assert first.parameters.as_mapping() == third.parameters.as_mapping()


def test_calibration_survives_noisy_quotes() -> None:
    generator = np.random.default_rng(20260831)
    clean = _observations()
    noise = 0.002
    noisy = SurfaceObservations(
        k=clean.k, T=clean.T, iv=clean.iv + noise * generator.standard_normal(clean.n)
    )
    fitted = HestonCalibrator().fit(noisy)
    predicted = fitted.implied_volatility(noisy.k, noisy.T)
    resolved = np.isfinite(predicted)
    rmse = float(np.sqrt(np.mean((predicted[resolved] - noisy.iv[resolved]) ** 2)))
    # The fit should land near the injected noise level: far below means it is
    # interpolating the noise, far above means it has not converged.
    assert 0.2 * noise < rmse < 5.0 * noise


