@pytest.mark.parametrize(
    "kwargs, message",
    [
        ({"v0": 0.0}, "v0 must be strictly positive"),
        ({"kappa": -1.0}, "kappa must be strictly positive"),
        ({"theta": 0.0}, "theta must be strictly positive"),
        ({"vol_of_vol": 0.0}, "vol_of_vol must be strictly positive"),
        ({"rho": 1.0}, "rho must lie strictly inside"),
        ({"v0": np.inf}, "v0 must be finite"),
    ],
)
def test_invalid_parameters_are_refused(kwargs, message) -> None:
    base = {"v0": 0.04, "kappa": 2.0, "theta": 0.04, "vol_of_vol": 0.3, "rho": -0.7}
    with pytest.raises(SurfaceValidationError, match=message):
        HestonParameters(**{**base, **kwargs})


def test_the_feller_ratio_is_reported_not_enforced() -> None:
    violating = HestonParameters(v0=0.04, kappa=0.5, theta=0.06, vol_of_vol=0.9, rho=-0.9)
    assert violating.satisfies_feller is False
    assert violating.feller_ratio == pytest.approx(2 * 0.5 * 0.06 / 0.81, rel=1e-12)


def test_the_parameters_carry_across_to_the_process_unchanged() -> None:
    process = TRUTH.to_process(drift=0.03)
    assert dict(process.params()) == {
        "kappa": TRUTH.kappa,
        "theta": TRUTH.theta,
        "vol_of_vol": TRUTH.vol_of_vol,
        "rho": TRUTH.rho,
        "drift": 0.03,
    }


def test_the_parameter_mapping_is_json_safe_plain_data() -> None:
    payload = TRUTH.parameters()
    assert json.loads(json.dumps(payload, allow_nan=False)) == payload


# --- the surface ---------------------------------------------------------------


def test_the_surface_needs_no_market_state() -> None:
    """In forward log-moneyness the forward divides out of price and strike.

    Passing a market must therefore change nothing, and *not* passing one must
    not raise -- unlike a computation that genuinely needs one, which raises
    rather than assuming a unit forward.
    """
    surface = HestonIVSurface(parameters=TRUTH)
    points = SurfacePoints(k=[-0.2, 0.0, 0.2], T=[1.0, 1.0, 1.0])
    without = surface.evaluate(points)
    with_market = surface.evaluate(
        points, market=SurfaceMarket.from_spot(spot=4321.0, T=[1.0], rate=0.05, carry=0.02)
    )
    np.testing.assert_array_equal(without.iv, with_market.iv)


def test_a_negative_correlation_skews_the_smile_downward_in_strike() -> None:
    surface = HestonIVSurface(parameters=TRUTH)
    k = np.linspace(-0.3, 0.3, 13)
    iv = surface.implied_volatility(k, np.full(k.size, 1.0))
    assert iv[0] > iv[-1]


def test_a_zero_correlation_smile_is_symmetric_about_the_money() -> None:
    # Not exactly symmetric -- the log-normal drift breaks it -- but the two
    # wings must be far closer to each other than under a -0.65 correlation.
    symmetric = HestonParameters(v0=0.045, kappa=1.8, theta=0.055, vol_of_vol=0.55, rho=0.0)
    k = np.array([-0.3, 0.3])
    flat = HestonIVSurface(parameters=symmetric).implied_volatility(k, np.full(2, 1.0))
    skewed = HestonIVSurface(parameters=TRUTH).implied_volatility(k, np.full(2, 1.0))
    assert abs(flat[0] - flat[1]) < 0.1 * abs(skewed[0] - skewed[1])


def test_the_surface_declines_wings_it_cannot_resolve() -> None:
    """The Fourier price has absolute accuracy, so a low-vega point is declined.

    This is the contract a definite surface owes: it either answers or says it
    will not, and never returns a plausible number it does not stand behind.
    """
    surface = HestonIVSurface(parameters=TRUTH)
    k = np.linspace(-1.5, 1.5, 31)
    T = np.full(k.size, 0.05)
    iv = surface.implied_volatility(k, T)
    uncertainty = surface.inversion_uncertainty(k, T)
    resolved = np.isfinite(iv)
    assert bool(np.any(resolved)) and bool(np.any(~resolved))
    assert bool(np.all(uncertainty[resolved] <= DEFAULT_IV_UNCERTAINTY_TOLERANCE))


def test_every_answered_point_is_accurate_to_the_declared_tolerance() -> None:
    """The declared tolerance is a measured guarantee, not a hope.

    Doubling the quadrature nodes twice over is an independent evaluation; a
    point the surface answered must agree between the two by less than the
    uncertainty it declared, or the guard is not doing its job.
    """
    coarse = HestonIVSurface(parameters=TRUTH, n_nodes=768)
    fine = HestonIVSurface(parameters=TRUTH, n_nodes=4096)
    k = np.linspace(-1.2, 1.2, 25)
    for maturity in (0.05, 0.25, 1.0, 3.0):
        T = np.full(k.size, maturity)
        left = coarse.implied_volatility(k, T)
        right = fine.implied_volatility(k, T)
        both = np.isfinite(left) & np.isfinite(right)
        if not bool(np.any(both)):
            continue
        assert float(np.max(np.abs(left - right)[both])) < DEFAULT_IV_UNCERTAINTY_TOLERANCE


def test_the_declared_price_noise_is_the_one_the_guard_uses() -> None:
    # The guard is uncertainty = noise / vega; at a point whose uncertainty is
    # exactly the tolerance, the vega is the ratio of the two constants.
    assert PRICE_NOISE_PER_UNIT_FORWARD > 0.0
    surface = HestonIVSurface(parameters=TRUTH)
    k = np.array([0.0])
    T = np.array([1.0])
    uncertainty = surface.inversion_uncertainty(k, T)
    assert 0.0 < float(uncertainty[0]) < DEFAULT_IV_UNCERTAINTY_TOLERANCE


def test_the_materialized_surface_passes_the_mesh_arbitrage_harness() -> None:
    """A model price comes from a martingale measure, so the mesh should be clean.

    The claim asserted is about the *mesh*, which is what was measured; the
    module docstring is explicit that the model's own arbitrage freedom is a
    different statement and that a finite grid can trip on wing noise.
    """
    grid = SurfaceGridSpec(k=np.linspace(-0.35, 0.35, 21), T=list(MATURITIES))
    report = materialize_surface(HestonIVSurface(parameters=TRUTH), grid).validate()
    assert report.passed is True, report.metrics


def test_total_variance_and_implied_volatility_agree() -> None:
    surface = HestonIVSurface(parameters=TRUTH)
    k = np.linspace(-0.3, 0.3, 9)
    T = np.full(k.size, 0.75)
    np.testing.assert_allclose(
        surface.total_variance(k, T),
        surface.implied_volatility(k, T) ** 2 * T,
        rtol=1e-14,
        atol=0.0,
    )


def test_evaluation_returns_rows_in_query_order() -> None:
    surface = HestonIVSurface(parameters=TRUTH)
    points = SurfacePoints(k=[0.2, -0.2, 0.0], T=[1.0, 1.0, 1.0])
    prediction = surface.evaluate(points)
    assert prediction.points.equals(points)
    np.testing.assert_array_equal(prediction.iv, surface.implied_volatility(points.k, points.T))


