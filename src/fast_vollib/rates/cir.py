r"""The Cox-Ingersoll-Ross affine term structure, in a numerically stable form.

Under the risk-neutral measure the short rate follows the square-root diffusion
of Cox, Ingersoll and Ross (1985),

.. math::

    dr_t = \kappa (\theta - r_t)\, dt + \sigma \sqrt{r_t}\, dW_t^{\mathbb{Q}},

and the zero-coupon bond price is affine in the state,
:math:`P(0, \tau) = A(\tau) e^{-B(\tau) r_0}`, with :math:`A` and :math:`B` given
in closed form by equation 23 of that paper.

The published form can overflow or lose precision in float64, and the
two obvious repairs each fail somewhere a caller will go.  This module is the
form that does not, so the derivation is recorded rather than left to be
rediscovered.

Writing :math:`\gamma = \sqrt{\kappa^2 + 2\sigma^2}` and :math:`\tau` for the
maturity, equation 23 reads

.. math::

    A(\tau) = \left[
        \frac{2\gamma e^{(\kappa + \gamma)\tau / 2}}
             {(\gamma + \kappa)(e^{\gamma\tau} - 1) + 2\gamma}
    \right]^{2\kappa\theta/\sigma^2},
    \qquad
    B(\tau) = \frac{2(e^{\gamma\tau} - 1)}
                   {(\gamma + \kappa)(e^{\gamma\tau} - 1) + 2\gamma}.

**Failure one: overflow.**  :math:`e^{\gamma\tau}` overflows past
:math:`\gamma\tau \approx 709`, which a thirty-year bond reaches at a
vol-of-rate of roughly 17 or more (depending on mean reversion).  Multiplying numerator and denominator through by
:math:`e^{-\gamma\tau}` and writing :math:`z = e^{-\gamma\tau} \in (0, 1]` fixes
that, and is where most implementations stop.

**Failure two: cancellation.**  That rearrangement leaves
:math:`\gamma - \kappa` to be formed by subtraction, and as :math:`\sigma \to 0`
those two agree to more and more digits.  At :math:`\sigma = 10^{-8}` the
subtraction has no significant digits left and the price comes back wrong in the
third decimal place -- measured at 5.5e-3 relative error against a fifty-digit
reference.  A vanishing vol-of-rate is not an exotic input: it is what a
deterministic-rate limit, a calibration starting point, and a finite-difference
sensitivity all walk through.

The fix is to never form the difference.  Since
:math:`\gamma^2 - \kappa^2 = 2\sigma^2`,

.. math::

    \delta := \gamma - \kappa = \frac{2\sigma^2}{\gamma + \kappa},

which is a *quotient of positive quantities* and avoids subtractive cancellation for small :math:`\sigma`.  With :math:`\delta` in hand the denominator becomes
:math:`(\gamma + \kappa) + \delta z`, and -- using
:math:`2\gamma = (\gamma + \kappa) + \delta` -- the affine base is

.. math::

    \frac{2\gamma}{(\gamma+\kappa) + \delta z} = \frac{1}{1 + x},
    \qquad x = -\frac{\delta (1 - z)}{2\gamma},

whose logarithm is :math:`-\log(1 + x)` with :math:`x \to 0` as
:math:`\sigma \to 0` -- exactly what :func:`math.log1p` exists for.  Finally
:math:`\frac{2\kappa\theta}{\sigma^2} \cdot \frac{\delta}{2} =
\frac{2\kappa\theta}{\gamma + \kappa}`, so the :math:`\sigma^2` in the exponent
cancels analytically instead of numerically.  What is left is
:func:`cir_affine_coefficients`.

Measured against ``mpmath`` at fifty digits, this form holds the relative error
in the *exponent* to under five units in the last place across the tested
parameter grid -- :math:`\sigma` from :math:`10^{-12}` to 5, maturities
to 500 years, :math:`\gamma\tau` past 3500.  The table is regenerated by
``scripts/generate_cir_reference_fixtures.py`` and pinned by
``tests/rates/test_reference_fixtures.py``.

There is **no** small-:math:`\sigma` threshold and no asymptotic branch.  The
only special case is :math:`\sigma` exactly zero, where the rate is
deterministic, :math:`2\kappa\theta/\sigma^2` is not a number, and the limit is
written out directly.

**Failure three: the complex logarithm.**  :func:`cir_integrated_rate_transform`
evaluates the same affine form at complex :math:`s`, and there the repair above
is silently undone by the backend.  NumPy, torch and JAX all compute a complex
``log1p`` as :math:`\log(1+z)` -- forming the sum first, which is exactly the
cancellation ``log1p`` exists to avoid.  Multiplied by the
:math:`2\kappa\theta/\sigma^2` standing in front of it, the lost digits are
amplified without bound as :math:`\sigma \to 0`: at :math:`\sigma = 10^{-6}` the
transform came back with a *relative error of 4e3*.  :func:`_log1p` restores it
with Kahan's decomposition and leaves the real path on the backend's own
``log1p``, bit for bit.

*The transform is the bond formula with an* :math:`s` *threaded through it,* and
that is what makes a transcription error hard to see: every wrong variant still
prices a bond, because at :math:`s = 1` the missing factor is one.  The detector is the small-:math:`\tau` expansion
:math:`\log A_s \approx -\kappa\theta s \tau^2 / 2`, whose two :math:`O(\tau)`
terms cancel only when the :math:`s` is present.  Unlike Heston's transform,
this one needs no branch bookkeeping at all, and that is a theorem rather than
an observation; :func:`cir_integrated_rate_coefficients` states it.

*This module is array-API native.*  It is written once against
:mod:`fast_vollib._array_api`, so the same code prices a bond from Python floats,
from a torch tensor that carries a gradient back to ``kappa``, and from a JAX
array under ``jit``.  It is the library's first analytic pricer with that
property; the Fourier pricers in :mod:`fast_vollib.pricing` are host-side
float64 by construction.

Parameterization is risk-neutral.  CIR's equation 23 carries a market price of
rate risk; ``kappa`` and ``theta`` here are the risk-neutral values with that
premium already absorbed, which is what a bond price needs and what a calibration
to bond data recovers.  Bakshi, Cao and Chen (1997) write the drift as
:math:`\theta_R - \kappa_R R`, so their parameters map on as
``kappa = kappa_R`` and ``theta = theta_R / kappa_R``.

The Feller ratio :math:`2\kappa\theta/\sigma^2` is reported by
:class:`~fast_vollib.rates.CIRDiscountCurve` and never enforced: calibrations
violate it routinely, the bond formula is well defined either way, and refusing
those parameters would make the library unable to represent the curves it exists
to fit.  CIR cannot produce a negative short rate; that is a property of the
model, stated rather than hidden.

References
----------
Cox, J. C., Ingersoll, J. E., Ross, S. A. (1985). A Theory of the Term Structure
of Interest Rates. *Econometrica* 53(2), 385-407, equation 23.

Bakshi, G., Cao, C., Chen, Z. (1997). Empirical Performance of Alternative
Option Pricing Models. *Journal of Finance* 52(5), 2003-2049.

Examples
--------
>>> from fast_vollib.rates import cir_discount_factor
>>> price = cir_discount_factor(
...     kappa=0.3, theta=0.04, volatility=0.1, initial_rate=0.04, maturity=1.0
... )
>>> float(round(price, 12))
0.960840811993

A zero maturity is worth exactly one, and no branch is needed to make it so --
every term of the exponent vanishes on its own:

>>> float(cir_discount_factor(
...     kappa=0.3, theta=0.04, volatility=0.1, initial_rate=0.04, maturity=0.0
... ))
1.0
"""

